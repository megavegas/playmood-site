window.PM_LANG = {
  current: "en",
  t(key, vars) {
    const pack = window.PM_I18N[this.current] || window.PM_I18N.en;
    let s = pack[key] || window.PM_I18N.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replaceAll("{" + k + "}", String(vars[k]));
      });
    }
    return s;
  },
  locale() {
    if (this.current === "fa") return "fa-IR";
    if (this.current === "ar") return "ar";
    return "en";
  },
  apply(lang) {
    const next = ["en", "fa", "ar"].includes(lang) ? lang : "en";
    this.current = next;
    localStorage.setItem("pm_lang", next);
    const rtl = next === "fa" || next === "ar";
    document.documentElement.lang = next === "fa" ? "fa" : next === "ar" ? "ar" : "en";
    document.documentElement.dir = rtl ? "rtl" : "ltr";
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = this.t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = this.t(el.getAttribute("data-i18n-html"));
    });
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      const on = btn.getAttribute("data-lang") === next;
      btn.setAttribute("aria-pressed", on ? "true" : "false");
      btn.classList.toggle("active", on);
    });
    document.title = next === "fa"
      ? "PlayMood — موزیک تو، حال تو"
      : next === "ar"
        ? "PlayMood — موسيقاك، مزاجك"
        : "PlayMood — Your music, your mood";
    window.dispatchEvent(new CustomEvent("pm:lang", { detail: { lang: next } }));
  },
  init() {
    const saved = localStorage.getItem("pm_lang");
    const start = ["en", "fa", "ar"].includes(saved) ? saved : "en";
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.addEventListener("click", () => this.apply(btn.getAttribute("data-lang")));
    });
    this.apply(start);
  }
};
